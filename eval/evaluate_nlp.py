def _load_labeled_dataset(
    file_path: str | None,
    default_data: list[tuple[str, str]],
) -> list[tuple[str, str]]:
    """Load (text, label) pairs from a CSV or JSON file, or return default_data."""
    if not file_path:
        return default_data

    path = Path(file_path)
    if not path.exists():
        raise FileNotFoundError(f"Dataset file not found: {path}")

    suffix = path.suffix.lower()
    rows: list[tuple[str, str]] = []

    if suffix == ".csv":
        with path.open("r", encoding="utf-8", newline="") as f:
            reader = csv.DictReader(f)
            if not reader.fieldnames:
                raise ValueError(f"CSV file has no header row: {path}")
            label_col = next(
                (c for c in ("label", "sentiment", "emotion", "target") if c in reader.fieldnames),
                None,
            )
            if "text" not in reader.fieldnames or label_col is None:
                raise ValueError(
                    f"CSV must contain 'text' and a label column ('label', 'sentiment', 'emotion', or 'target'): {path}"
                )
            for row in reader:
                text = (row.get("text") or "").strip()
                label = (row.get(label_col) or "").strip()
                if text and label:
                    rows.append((text, label))
    elif suffix == ".json":
        data = json.loads(path.read_text(encoding="utf-8"))
        if not isinstance(data, list):
            raise ValueError(f"JSON dataset must be a list of objects or [text, label] pairs: {path}")
        for item in data:
            if isinstance(item, dict):
                text = str(item.get("text", "")).strip()
                label = str(
                    item.get("label") or item.get("sentiment") or item.get("emotion") or ""
                ).strip()
            elif isinstance(item, (list, tuple)) and len(item) >= 2:
                text = str(item[0]).strip()
                label = str(item[1]).strip()
            else:
                continue
            if text and label:
                rows.append((text, label))
    else:
        raise ValueError(f"Unsupported dataset format '{suffix}'. Use .csv or .json.")

    if not rows:
        raise ValueError(f"No valid (text, label) samples found in {path}")
    return rows


def _safe_metric(fn, y_true: list[str], y_pred: list[str]) -> float:
    """Compute scalar agreement metrics safely when only one label is present."""
    if len(set(y_true) | set(y_pred)) < 2:
        return 1.0 if y_true == y_pred else 0.0
    val = float(fn(y_true, y_pred))
    return 0.0 if math.isnan(val) else round(val, 4)


def _compute_classification_metrics(
    y_true: list[str],
    y_pred: list[str],
    labels: list[str],
) -> dict:
    """Compute accuracy, macro/weighted P/R/F1, kappa, MCC, and confusion matrices."""
    acc = accuracy_score(y_true, y_pred)
    macro_p, macro_r, macro_f1, _ = precision_recall_fscore_support(
        y_true, y_pred, labels=labels, average="macro", zero_division=0
    )
    weighted_p, weighted_r, weighted_f1, _ = precision_recall_fscore_support(
        y_true, y_pred, labels=labels, average="weighted", zero_division=0
    )
    cm = confusion_matrix(y_true, y_pred, labels=labels)
    cm_norm = confusion_matrix(y_true, y_pred, labels=labels, normalize="true")
    report = classification_report(y_true, y_pred, labels=labels, zero_division=0)

    return {
        "samples": len(y_true),
        "labels": labels,
        "accuracy": round(float(acc), 4),
        "macro_precision": round(float(macro_p), 4),
        "macro_recall": round(float(macro_r), 4),
        "macro_f1": round(float(macro_f1), 4),
        "weighted_precision": round(float(weighted_p), 4),
        "weighted_recall": round(float(weighted_r), 4),
        "weighted_f1": round(float(weighted_f1), 4),
        "cohens_kappa": _safe_metric(cohen_kappa_score, y_true, y_pred),
        "mcc": _safe_metric(matthews_corrcoef, y_true, y_pred),
        "confusion_matrix": cm.tolist(),
        "confusion_matrix_normalized": [[round(float(v), 4) for v in row] for row in cm_norm],
        "report": report,
    }


def _format_confusion_matrix(
    matrix: list[list[int | float]],
    labels: list[str],
    normalized: bool = False,
) -> str:
    """Render an aligned confusion matrix table (rows = actual, cols = predicted)."""
    col_width = max(max((len(lbl) for lbl in labels), default=5), 7) + 2
    header_lbl = "Actual \\ Pred"
    row_lbl_width = max(len(header_lbl), max((len(lbl) for lbl in labels), default=5)) + 2

    lines = [
        "    " + header_lbl.ljust(row_lbl_width) + "".join(lbl.rjust(col_width) for lbl in labels)
    ]
    for label, row in zip(labels, matrix):
        cells = "".join(
            (f"{val:.2f}" if normalized else str(int(val))).rjust(col_width) for val in row
        )
        lines.append("    " + label.ljust(row_lbl_width) + cells)
    return "\n".join(lines)


def evaluate_sentiment(dataset: list[tuple[str, str]] | None = None) -> dict:
    data = dataset if dataset is not None else SENTIMENT_BENCHMARK
    y_true = [label for _, label in data]
    y_pred = [score_sentiment(text)["label"] for text, _ in data]
    extra_labels = sorted((set(y_true) | set(y_pred)) - set(SENTIMENT_LABELS))
    labels = SENTIMENT_LABELS + extra_labels
    return _compute_classification_metrics(y_true, y_pred, labels)


def evaluate_emotions(dataset: list[tuple[str, str]] | None = None) -> dict:
    data = dataset if dataset is not None else EMOTION_BENCHMARK
    y_true = [emo for _, emo in data]
    y_pred = [score_emotions(text)["dominant_emotion"] for text, _ in data]
    extra_labels = sorted((set(y_true) | set(y_pred)) - set(EMOTION_LABELS))
    labels = EMOTION_LABELS + extra_labels
    metrics = _compute_classification_metrics(y_true, y_pred, labels)
    metrics["predictions"] = list(zip(y_true, y_pred))
    return metrics


def evaluate_summarization() -> dict:
    scorer = rouge_scorer.RougeScorer(["rouge1", "rouge2", "rougeL"], use_stemmer=True)
    r1_scores, r2_scores, rl_scores = [], [], []
    for case in SUMMARIZATION_BENCHMARK:
        prep = preprocess_text(case["text"])
        summary_items = extractive_summarize(prep["sentences"], top_k=3)
        predicted = " ".join(item["text"] for item in summary_items)
        scores = scorer.score(case["reference"], predicted)
        r1_scores.append(scores["rouge1"].fmeasure)
        r2_scores.append(scores["rouge2"].fmeasure)
        rl_scores.append(scores["rougeL"].fmeasure)

    n = len(SUMMARIZATION_BENCHMARK)
    return {
        "samples": n,
        "rouge1_f1": round(sum(r1_scores) / n, 4),
        "rouge2_f1": round(sum(r2_scores) / n, 4),
        "rougeL_f1": round(sum(rl_scores) / n, 4),
    }


def evaluate_retrieval() -> dict:
    hits_at_1 = 0
    hits_at_3 = 0
    reciprocal_ranks = []
    total = 0

    for bundle in RETRIEVAL_BENCHMARK:
        for query, expected_idx in bundle["queries"]:
            total += 1
            results = retrieve_top_chunks_tfidf(bundle["chunks"], query, top_k=3)
            ranked_ids = [r["chunk_index"] for r in results]
            if ranked_ids and ranked_ids[0] == expected_idx:
                hits_at_1 += 1
            if expected_idx in ranked_ids:
                hits_at_3 += 1
                reciprocal_ranks.append(1.0 / (ranked_ids.index(expected_idx) + 1))
            else:
                reciprocal_ranks.append(0.0)

    return {
        "queries": total,
        "recall_at_1": round(hits_at_1 / total, 4),
        "recall_at_3": round(hits_at_3 / total, 4),
        "mrr": round(sum(reciprocal_ranks) / total, 4),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description="Evaluate NLP pipeline metrics.")
    parser.add_argument("--json", action="store_true", help="Output metrics as JSON")
    parser.add_argument(
        "--sentiment-file",
        type=str,
        default=None,
        help="Optional CSV or JSON file with labeled sentiment samples (columns/keys: text, label)",
    )
    parser.add_argument(
        "--emotion-file",
        type=str,
        default=None,
        help="Optional CSV or JSON file with labeled emotion samples (columns/keys: text, label)",
    )
    args = parser.parse_args()

    sentiment_data = _load_labeled_dataset(args.sentiment_file, SENTIMENT_BENCHMARK)
    emotion_data = _load_labeled_dataset(args.emotion_file, EMOTION_BENCHMARK)

    t0 = time.perf_counter()
    sentiment_metrics = evaluate_sentiment(sentiment_data)
    emotion_metrics = evaluate_emotions(emotion_data)
    rouge_metrics = evaluate_summarization()
    retrieval_metrics = evaluate_retrieval()
    elapsed_ms = round((time.perf_counter() - t0) * 1000, 2)

    results = {
        "elapsed_ms": elapsed_ms,
        "sentiment": {k: v for k, v in sentiment_metrics.items() if k != "report"},
        "emotion": {k: v for k, v in emotion_metrics.items() if k != "report"},
        "summarization_rouge": rouge_metrics,
        "tfidf_retrieval": retrieval_metrics,
    }

    if args.json:
        print(json.dumps(results, indent=2))
        return

    print("=" * 68)
    print("YouTube NLP & RAG Studio - Evaluation Report")
    print("=" * 68)
    print(f"Total benchmark runtime: {elapsed_ms} ms\n")
